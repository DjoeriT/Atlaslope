#!/usr/bin/env python3
"""France WSET L3 place list (decision #53, owner 22 Oct 2026: the WSET list first, region by region). Costs no tokens.

Usage: fr_wset.py [--sources]   (in a worktree set ATLASLOPE_RAW=<main checkout>/data/raw)

Reads the name table in Review/countries/france-prep/wset-l3-names.md (rows with an EU register file number), joins each to
data/countries/fr/register.json (current single document = last summary sheet) and to the INAO parcel shapefile's names, and
writes data/countries/fr/wset-places.json: id, name, batch, fileNumber, single document attachment, INAO app/denom for the
outline cut. Prints one line per place that lacks a single document text or an INAO outline, then a summary.
--sources also copies each single document text to Review/sources/fetched/att-<fileNumber>-<attachment>.txt and cuts it with
Tools/guides/extract.py into Review/guides-pipeline/fr-<batch>/<id>.extract.txt with that batch's manifest.json (the route in
docs/PROJECT.md "Run a region locally", step 2). A place without a single document is listed for its INAO cahier des charges.
"""
import csv
import io
import json
import os
import shutil
import sys
import re
import subprocess
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RAW = Path(os.environ.get("ATLASLOPE_RAW", ROOT / "data/raw")) / "countries/fr"
TABLE = ROOT / "Review/countries/france-prep/wset-l3-names.md"
OUT = ROOT / "data/countries/fr/wset-places.json"


def norm(s: str) -> str:
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode().lower()
    return re.sub(r"[^a-z0-9]+", " ", s).strip()


def slug(s: str) -> str:
    return norm(s).replace(" ", "-")


def inao_names() -> dict:
    shp = next(RAW.glob("shp/*.shp"))
    sql = f'SELECT DISTINCT app, denom FROM "{shp.stem}"'
    out = subprocess.run(["ogr2ogr", "-f", "CSV", "/vsistdout/", str(shp), "-dialect", "sqlite", "-sql", sql],
                         check=True, capture_output=True, text=True).stdout
    names = {}
    for r in csv.DictReader(io.StringIO(out)):
        for alias in r["denom"].split(" ou "):  # INAO spells alternatives as "Hermitage ou Ermitage ou ..."
            names.setdefault(norm(alias), (r["app"], r["denom"]))
    return names


def main() -> None:
    reg = {e["fileNumber"]: e for e in json.loads((ROOT / "data/countries/fr/register.json").read_text())["entries"]}
    inao = inao_names()
    places, seen = [], set()
    for line in TABLE.read_text(encoding="utf-8").splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 7 or not re.fullmatch(r"P[DG]O-FR-[A-Z]\d+", cells[3]):
            continue
        heading, name, kind, fn, regname, note, batch = cells[:7]
        pid = slug(name)
        if pid in seen:
            continue
        seen.add(pid)
        e = reg.get(fn, {})
        att = (e.get("summarySheets") or [None])[-1]
        hit = inao.get(norm(regname)) or inao.get(norm(name))
        places.append({"id": pid, "name": name, "registerName": regname, "batch": batch, "heading": heading, "kind": kind,
                       "fileNumber": fn, "type": e.get("type"), "singleDocument": att,
                       "inao": {"app": hit[0], "denom": hit[1]} if hit else None})
    OUT.write_text(json.dumps({"$comment": "Generated by Tools/countries/fr_wset.py; do not edit by hand.",
                               "places": places}, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    no_doc = [p["id"] for p in places if not (p["singleDocument"] and (RAW / "att" / f"{p['singleDocument']}.txt").exists())]
    no_inao = [p["id"] for p in places if not p["inao"]]
    print(f"{len(places)} places -> {OUT.relative_to(ROOT)}")
    print(f"no single document text: {len(no_doc)} {' '.join(no_doc)}")
    print(f"no INAO outline: {len(no_inao)} {' '.join(no_inao)}")
    if "--sources" in sys.argv:
        sources(places)
    by = {}
    for p in places:
        by[p["batch"]] = by.get(p["batch"], 0) + 1
    print("batches:", ", ".join(f"{k} {v}" for k, v in sorted(by.items(), key=lambda x: -x[1])))


def sources(places: list) -> None:
    fetched = ROOT / "Review/sources/fetched"
    manifests = {}
    for p in places:
        if not p["singleDocument"]:
            continue
        raw = RAW / "att" / f"{p['singleDocument']}.txt"
        if not raw.exists():
            continue
        txt = fetched / f"att-{p['fileNumber']}-{p['singleDocument']}.txt"
        shutil.copyfile(raw, txt)
        gp = ROOT / "Review/guides-pipeline" / f"fr-{slug(p['batch'])}"
        gp.mkdir(parents=True, exist_ok=True)
        subprocess.run([sys.executable, str(ROOT / "Tools/guides/extract.py"), str(txt), str(gp / f"{p['id']}.extract.txt")],
                       check=True, capture_output=True)
        manifests.setdefault(gp, {})[f"{p['id']}-doc"] = str(txt.relative_to(ROOT))
    for gp, m in manifests.items():
        (gp / "manifest.json").write_text(json.dumps({"sources": m}, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"sources: {gp.relative_to(ROOT)}: {len(m)} places")


if __name__ == "__main__":
    main()
